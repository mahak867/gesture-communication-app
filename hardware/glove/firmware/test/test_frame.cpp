// Host unit tests for glove_frame.h. Build & run:  make -C hardware/glove/firmware/test
// With an output path, also writes golden vectors that the app's TypeScript
// decoder must read identically (__tests__/firmware-compat.test.ts).
#include <cassert>
#include <cstdio>
#include <cstring>
#include "../gesturetalk_glove/glove_frame.h"

using namespace glove;
static int failures = 0;
#define CHECK(c) do { if (!(c)) { std::fprintf(stderr, "FAIL %s:%d  %s\n", __FILE__, __LINE__, #c); failures++; } } while (0)

struct Vec { uint16_t flex[5]; int16_t acc[3]; int8_t gyro[3]; bool button; uint8_t seq; };

static const Vec VECTORS[] = {
  {{1200, 1250, 1300, 1350, 1400}, {0, 0, 1000}, {0, 0, 0}, false, 0},
  {{0, 65535, 3300, 1, 2048}, {-32768, 32767, -1}, {-128, 127, -1}, true, 127},
  {{2400, 2100, 900, 1500, 3100}, {-707, 12, 707}, {31, -16, 5}, true, 200},  // seq wraps to 7 bits
};

int main(int argc, char **argv) {
  // Packing layout
  uint8_t b[FRAME_BYTES];
  packFrame(b, VECTORS[0].flex, VECTORS[0].acc, VECTORS[0].gyro, false, 5);
  CHECK(b[0] == (1200 & 0xFF) && b[1] == (1200 >> 8));
  CHECK(b[14] == (1000 & 0xFF) && b[15] == (1000 >> 8));
  CHECK(b[19] == 5);
  packFrame(b, VECTORS[1].flex, VECTORS[1].acc, VECTORS[1].gyro, true, 127);
  CHECK(b[10] == 0x00 && b[11] == 0x80);  // -32768 little-endian
  CHECK(b[16] == 0x80 && b[17] == 0x7F);  // int8 -128, 127
  CHECK(b[19] == 0xFF);                   // button + seq 127
  packFrame(b, VECTORS[2].flex, VECTORS[2].acc, VECTORS[2].gyro, false, 200);
  CHECK(b[19] == (200 & 0x7F));

  // Sensor conversions
  CHECK(accelRawToMg(16384) == 1000);
  CHECK(accelRawToMg(-8192) == -500);
  CHECK(gyroRawToDiv8(0) == 0);
  CHECK(gyroRawToDiv8(655 * 8) == 10);   // 80 °/s → 10
  CHECK(gyroRawToDiv8(32767) == 62);     // 500 °/s full scale → 62
  CHECK(gyroRawToDiv8(-32768) == -62);

  // Battery
  CHECK(batteryPercentFromMv(4200) == 100);
  CHECK(batteryPercentFromMv(3300) == 0);
  CHECK(batteryPercentFromMv(3000) == 0);
  CHECK(batteryPercentFromMv(3725) == 50);

  // BUZZ command parsing
  CHECK(parseBuzzMs("BUZZ 120") == 120);
  CHECK(parseBuzzMs("  buzz 5") == 10);       // clamped up
  CHECK(parseBuzzMs("BUZZ 99999999") == 1000); // clamped down, no overflow
  CHECK(parseBuzzMs("BUZZ") == 80);
  CHECK(parseBuzzMs("BUZZ\n") == 80);
  CHECK(parseBuzzMs("BUZZER 10") == 0);
  CHECK(parseBuzzMs("CAL") == 0);
  CHECK(parseBuzzMs("") == 0);

  // Sensor fault detection
  CHECK(flexLooksDisconnected(0));
  CHECK(flexLooksDisconnected(3300));
  CHECK(!flexLooksDisconnected(1500));

  if (argc > 1) {
    FILE *f = std::fopen(argv[1], "w");
    std::fprintf(f, "{\n  \"note\": \"Generated by hardware/glove/firmware/test/test_frame.cpp. Do not edit.\",\n  \"vectors\": [\n");
    int n = sizeof(VECTORS) / sizeof(VECTORS[0]);
    for (int k = 0; k < n; k++) {
      const Vec &v = VECTORS[k];
      packFrame(b, v.flex, v.acc, v.gyro, v.button, v.seq);
      std::fprintf(f, "    {\"flex\": [%u, %u, %u, %u, %u], \"accelMg\": [%d, %d, %d], \"gyroDiv8\": [%d, %d, %d], \"button\": %s, \"seq\": %u, \"bytes\": [",
                   v.flex[0], v.flex[1], v.flex[2], v.flex[3], v.flex[4], v.acc[0], v.acc[1], v.acc[2], v.gyro[0], v.gyro[1], v.gyro[2],
                   v.button ? "true" : "false", v.seq & 0x7F);
      for (int i = 0; i < FRAME_BYTES; i++) std::fprintf(f, "%s%u", i ? ", " : "", b[i]);
      std::fprintf(f, "]}%s\n", k + 1 < n ? "," : "");
    }
    std::fprintf(f, "  ]\n}\n");
    std::fclose(f);
  }

  if (failures) { std::fprintf(stderr, "%d check(s) failed\n", failures); return 1; }
  std::puts("glove_frame: all checks passed");
  return 0;
}
